/**
 * Embed the definitions bundled with this package (map-views/*.json5) as a module, so `loadMapViewDefinitions`
 * finds them in any bundle without a path to this package's folder.
 *
 *   bun run generate:definitions
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DEFINITIONS_DIR = join(import.meta.dir, '../map-views');
export const OUTPUT = join(import.meta.dir, '../src/node/bundled-definitions.ts');

/** The module's source for the definitions currently in map-views/. */
export function render(): string {
  const entries = readdirSync(DEFINITIONS_DIR)
    .filter((file) => file.endsWith('.json5'))
    .sort()
    .map((file) => `  ${JSON.stringify(file)}: ${JSON.stringify(readFileSync(join(DEFINITIONS_DIR, file), 'utf8'))},`);
  return [
    '// Generated by scripts/generate-definitions.ts from map-views/*.json5. Do not edit.',
    'export const BUNDLED_DEFINITIONS: Record<string, string> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

if (import.meta.main) {
  writeFileSync(OUTPUT, render());
  console.log(`bundled definitions → ${OUTPUT}`);
}
